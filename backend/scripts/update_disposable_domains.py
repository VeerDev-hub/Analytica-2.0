"""Refresh app/core/data/disposable_domains.txt from the two maintained public lists.

    docker compose exec api python scripts/update_disposable_domains.py

Rebuild/redeploy afterwards (the file ships inside the image). Domains in
app.core.emails.ALLOWED_PROVIDERS are dropped even if a list includes them.
"""

from __future__ import annotations

import re
import sys
import urllib.request
from pathlib import Path

SOURCES = [
    "https://raw.githubusercontent.com/disposable-email-domains/disposable-email-domains/main/disposable_email_blocklist.conf",
    "https://raw.githubusercontent.com/disposable/disposable-email-domains/master/domains.txt",
]
OUT = Path(__file__).resolve().parents[1] / "app" / "core" / "data" / "disposable_domains.txt"
VALID = re.compile(r"^[a-z0-9.-]+\.[a-z]{2,}$")

HEADER = """# Disposable / temporary email domains, one per line. Generated by
# backend/scripts/update_disposable_domains.py from:
#   https://github.com/disposable-email-domains/disposable-email-domains (CC0)
#   https://github.com/disposable/disposable-email-domains (MIT)
"""


def main() -> int:
    sys.path.insert(0, str(OUT.parents[3]))
    from app.core.emails import ALLOWED_PROVIDERS

    domains: set[str] = set()
    for url in SOURCES:
        with urllib.request.urlopen(url, timeout=30) as r:  # noqa: S310 - fixed https URLs
            text = r.read().decode("utf-8", "replace")
        got = {ln.strip().lower() for ln in text.splitlines()}
        got = {d for d in got if VALID.match(d)}
        print(f"{len(got):>7} domains from {url}")
        domains |= got
    dropped = domains & ALLOWED_PROVIDERS
    domains -= ALLOWED_PROVIDERS
    if dropped:
        print("ignored (allowlisted):", ", ".join(sorted(dropped)))
    if len(domains) < 1000:
        print("refusing to write: suspiciously few domains", file=sys.stderr)
        return 1
    OUT.write_text(HEADER + "\n".join(sorted(domains)) + "\n", encoding="utf-8")
    print(f"{len(domains):>7} domains written to {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
