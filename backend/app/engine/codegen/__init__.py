"""CodeGenerator (class diagram 3.4): the exported script must match the UI result.

Fitted steps embed what they learned on the training rows (fill values, bounds, category
lists, scaler parameters), so running the script on the original file reproduces the
exported data without refitting. Rows are assigned to partitions using the exported
`__split__` column when present.
"""

from __future__ import annotations

import json
import textwrap

from ..transforms import registry

HEADER = '''"""Generated by Analytica Studio — {title}

Reproduces the cleaning and feature steps recorded in the project pipeline.
Usage:  python {filename} path/to/{source}
"""
import sys

import numpy as np
import pandas as pd

SOURCE = sys.argv[1] if len(sys.argv) > 1 else {source!r}
TARGET = {target!r}

df = pd.read_csv(SOURCE) if SOURCE.endswith((".csv", ".txt")) else (
    pd.read_parquet(SOURCE) if SOURCE.endswith(".parquet") else pd.read_excel(SOURCE))
'''


def _block(i: int, step: dict) -> str:
    t = registry.get(step["step_type"])
    try:
        body = t.code(step.get("params") or {}, step.get("state") or {})
    except Exception as e:  # noqa: BLE001
        body = f"# could not generate code: {e}"
    note = " (values learned on training rows)" if t.requires_fit else ""
    disabled = "" if step.get("is_enabled", True) else "# DISABLED in the UI:\n"
    code = textwrap.indent(body, "# " if disabled else "")
    return f"# --- Step {i}: {t.describe(step.get('params') or {})}{note}\n{disabled}{code}\n"


def to_script(
    steps: list[dict], *, title: str, source: str, target: str | None, filename: str = "pipeline.py"
) -> str:
    parts = [HEADER.format(title=title, filename=filename, source=source, target=target)]
    for i, s in enumerate(steps, 1):
        parts.append(_block(i, s))
    parts.append(
        textwrap.dedent("""
        # --- Partitions
        if "__split__" in df.columns:
            train, val, test = (df[df["__split__"] == p].drop(columns="__split__")
                                for p in ("train", "val", "test"))
        else:
            train, val, test = df, df.iloc[:0], df.iloc[:0]
        if TARGET:
            X_train, y_train = train.drop(columns=[TARGET]), train[TARGET]
            X_test, y_test = test.drop(columns=[TARGET]), test[TARGET]

        if __name__ == "__main__":
            print(df.shape)
            df.to_csv("prepared.csv", index=False)
    """)
    )
    return "\n".join(parts)


def to_notebook(steps: list[dict], *, title: str, source: str, target: str | None) -> bytes:
    def md(text: str) -> dict:
        return {"cell_type": "markdown", "metadata": {}, "source": text.splitlines(True)}

    def code(text: str) -> dict:
        return {
            "cell_type": "code",
            "metadata": {},
            "execution_count": None,
            "outputs": [],
            "source": text.strip("\n").splitlines(True),
        }

    cells = [
        md(f"# {title}\nGenerated by Analytica Studio. Each cell is one pipeline step."),
        code(
            f"import numpy as np\nimport pandas as pd\n\nSOURCE = {source!r}\n"
            f"TARGET = {target!r}\ndf = pd.read_csv(SOURCE)\ndf.head()"
        ),
    ]
    for i, s in enumerate(steps, 1):
        t = registry.get(s["step_type"])
        cells.append(md(f"### Step {i}: {t.describe(s.get('params') or {})}\n{t.explain_text}"))
        cells.append(code(_block(i, s)))
    cells.append(code("df.describe(include='all').T"))
    nb = {
        "cells": cells,
        "metadata": {
            "kernelspec": {"name": "python3", "language": "python", "display_name": "Python 3"}
        },
        "nbformat": 4,
        "nbformat_minor": 5,
    }
    return json.dumps(nb, indent=1).encode()


